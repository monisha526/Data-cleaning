# LEVEL 1 - DATA CLEANING
# Data Analytics Internship

import pandas as pd

# 1. Load Dataset from GitHub
url = "https://raw.githubusercontent.com/datasciencedojo/datasets/master/titanic.csv"

data = pd.read_csv(url)

print("ORIGINAL DATASET")
print(data.head())

# 2. Dataset Information
print("\nDataset Shape:", data.shape)

print("\nMissing Values:")
print(data.isnull().sum())

print("\nDuplicate Values:", data.duplicated().sum())

print("\nColumn Data Types:")
print(data.dtypes)

# 3. Handle Missing Values
data["Age"] = data["Age"].fillna(data["Age"].median())

data["Embarked"] = data["Embarked"].fillna(
    data["Embarked"].mode()[0]
)

# Remove Cabin column due to excessive missing values
data.drop(columns=["Cabin"], inplace=True)

# 4. Remove Duplicate Records
data.drop_duplicates(inplace=True)

# 5. Correct Data Types
data["PassengerId"] = data["PassengerId"].astype("int64")
data["Survived"] = data["Survived"].astype("int64")
data["Pclass"] = data["Pclass"].astype("int64")
data["Age"] = data["Age"].astype("float64")

# 6. Final Verification
print("\nCLEANED DATASET")
print(data.head())

print("\nRemaining Missing Values:")
print(data.isnull().sum())

print("\nRemaining Duplicates:", data.duplicated().sum())

print("\nFinal Dataset Shape:", data.shape)

# 7. Save Cleaned Dataset
data.to_csv("Titanic_Cleaned.csv", index=False)

print("\nSUCCESS: Cleaned dataset saved!")